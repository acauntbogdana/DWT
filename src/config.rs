// Константы конфигурации для DWT-исследования (Last-out-first-in DWT model).

// Пути к данным
pub const DEEP_DIR: &str = r"Ваш адрес:\IEX\DEEP";
pub const OUTPUT_DIR: &str = r"Ваш адрес";

// Параметры построения баров
pub const BAR_INTERVAL_MIN: i64 = 1;

// Параметры DWT-модели
/// Порог амплитуды δ для подтверждения локальных экстремумов.
///
/// В статье (4) δ записан как абсолютная величина: |p_t - p_t'| > δ.
/// Здесь используется ОТНОСИТЕЛЬНЫЙ порог: |x_new - x_last| / |x_last| > DELTA_REL.
/// Это осознанное отклонение от текста статьи: цены разных тикеров
/// отличаются на порядки (от ~$1 до ~$1000+), и абсолютный δ давал бы
/// несопоставимое поведение детектора разворотов по инструментам.
/// Значение 0.005 = 0.5% — типичный размер значимого разворота на минутных барах.
pub const DELTA_REL: f64 = 0.005;
/// Минимальное число баров для тикера
pub const MIN_BARS: usize = 500;
/// Прогрев: сколько первых наблюдений не используем для теста
pub const WARMUP_BARS: usize = 200;

// Параметры VaR
/// Уровень квантиля τ (5% → VaR на уровне 95%).
pub const VAR_LEVEL: f64 = 0.05;
/// Коэффициент экспоненциального забывания для EWMA.
pub const EWMA_LAMBDA: f64 = 0.94;

// Горизонты прогноза (в барах, т.е. в минутах при 1-мин барах)
pub const HORIZONS: &[usize] = &[1, 5, 15, 30];

// Параметры DM/GDM
/// Число bootstrap-репликаций для p-values.
pub const BOOTSTRAP_B: usize = 1000;
/// Ширина полосы для QS-ядра (Andrews 1991).
/// QS1 = 1.3221 * N^(1/5), QS2 = 1.80 * N^(1/5).
pub const QS_KERNEL_COEF: f64 = 1.80;
/// Минимальное число наблюдений для DM-теста.
pub const MIN_DM_OBS: usize = 100;

/// Длина скользящего окна (в барах) для бенчмарка "скользящее среднее"
/// в тестах предсказания среднего.
pub const WINDOW_BARS: usize = 60;